"""Submission verification must compare complete bytes and the official schema."""

from __future__ import annotations

import hashlib
import json
import subprocess
from pathlib import Path

import pytest

from tools import verify_docker

REPO = Path(__file__).resolve().parents[1]


@pytest.fixture
def runtime_root(tmp_path):
    root = tmp_path / "checkout"
    files = {
        "engine/main.py": b"print('engine')\n",
        "renderer/convert.py": b"CONVERTER = 1\n",
        "brand_kit/assets/logo.png": b"original supplied asset",
        "brand_kit/fonts/Regular.ttf": b"original supplied font",
        "requirements.txt": b"Pillow==11.0.0\n",
        "models/fit_policy/default.json": b'{"schema_version": 1}\n',
        "chameleon_design_schema_v0.9.json": (
            REPO / "chameleon_design_schema_v0.9.json"
        ).read_bytes(),
    }
    for name, content in files.items():
        path = root / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(content)
    return root


def test_complete_matching_runtime_is_accepted(runtime_root):
    packaged = verify_docker.runtime_file_hashes(runtime_root)

    verify_docker.verify_packaged_files(packaged, root=runtime_root)

    assert (
        packaged["brand_kit/fonts/Regular.ttf"]
        == hashlib.sha256(b"original supplied font").hexdigest()
    )
    assert "models/fit_policy/default.json" in packaged


@pytest.mark.parametrize(
    ("difference", "name"),
    [
        ("changed", "engine/main.py"),
        ("changed", "brand_kit/fonts/Regular.ttf"),
        ("missing", "brand_kit/assets/logo.png"),
        ("unexpected", "engine/obsolete.py"),
    ],
)
def test_stale_missing_and_unexpected_runtime_files_fail(runtime_root, difference, name):
    packaged = verify_docker.runtime_file_hashes(runtime_root)
    if difference == "missing":
        packaged.pop(name)
    else:
        packaged[name] = hashlib.sha256(b"different image bytes").hexdigest()

    with pytest.raises(RuntimeError, match="Image differs from submission files") as caught:
        verify_docker.verify_packaged_files(packaged, root=runtime_root)

    assert name in str(caught.value)
    assert f"{difference}=['{name}']" in str(caught.value)


def test_new_checkout_file_omitted_from_old_image_fails(runtime_root):
    old_image = verify_docker.runtime_file_hashes(runtime_root)
    (runtime_root / "engine" / "new_submission_module.py").write_text(
        "NEW_FEATURE = True\n", encoding="utf-8"
    )

    with pytest.raises(RuntimeError, match="new_submission_module.py") as caught:
        verify_docker.verify_packaged_files(old_image, root=runtime_root)

    assert "missing=['engine/new_submission_module.py']" in str(caught.value)


def test_generated_python_byte_caches_do_not_change_runtime_identity(runtime_root):
    packaged = verify_docker.runtime_file_hashes(runtime_root)
    cache = runtime_root / "engine" / "__pycache__"
    cache.mkdir()
    (cache / "main.cpython-311.pyc").write_bytes(b"generated bytecode")
    (cache / "generated.json").write_bytes(b"also generated inside cache")
    (runtime_root / "renderer" / "convert.pyc").write_bytes(b"legacy bytecode")

    assert verify_docker.runtime_file_hashes(runtime_root) == packaged
    verify_docker.verify_packaged_files(packaged, root=runtime_root)


@pytest.fixture
def sample_design():
    task = json.loads(
        (REPO / "input" / "chameleon_sample_level1_warmup.json").read_text(encoding="utf-8")
    )
    return task["source"]


def write_output(directory, design):
    directory.mkdir()
    name = "warmup_output.json"
    (directory / name).write_text(json.dumps(design), encoding="utf-8")
    return [{"output_json": name}]


def test_actual_official_sample_passes_official_schema(tmp_path, sample_design):
    artifacts = tmp_path / "artifacts"
    rows = write_output(artifacts, sample_design)

    verify_docker.verify_output_schemas(artifacts, rows)

    assert rows == [{"output_json": "warmup_output.json", "schema_valid": True}]


@pytest.mark.parametrize("invalid", ["additional_field", "zero_canvas", "fractional_canvas"])
def test_official_schema_rejects_invalid_output(tmp_path, sample_design, invalid):
    if invalid == "additional_field":
        sample_design["unrecognized_submission_field"] = True
    elif invalid == "zero_canvas":
        sample_design["canvas"]["width"] = 0
    else:
        sample_design["canvas"]["height"] = 1080.5
    artifacts = tmp_path / "artifacts"
    rows = write_output(artifacts, sample_design)

    with pytest.raises(RuntimeError, match="Official schema rejected warmup_output.json"):
        verify_docker.verify_output_schemas(artifacts, rows)

    assert "schema_valid" not in rows[0]


@pytest.mark.parametrize("artifact_name", ["../outside.json", "subdir/output.json", "absolute"])
def test_artifact_path_escape_is_rejected(tmp_path, sample_design, artifact_name):
    artifacts = tmp_path / "artifacts"
    artifacts.mkdir()
    outside = tmp_path / "outside.json"
    outside.write_text(json.dumps(sample_design), encoding="utf-8")
    if artifact_name == "absolute":
        artifact_name = str(outside.resolve())

    with pytest.raises(RuntimeError, match="Invalid output artifact name"):
        verify_docker.verify_output_schemas(artifacts, [{"output_json": artifact_name}])


def test_skip_build_cannot_report_pass_for_stale_image(tmp_path, runtime_root, monkeypatch, capsys):
    packaged = verify_docker.runtime_file_hashes(runtime_root)
    (runtime_root / "engine" / "new_submission_module.py").write_text(
        "NEW_FEATURE = True\n", encoding="utf-8"
    )
    commands = []
    image_id = "sha256:immutable-tested-image"

    def capture(command):
        commands.append(command)
        if command[:3] == ["docker", "image", "inspect"]:
            return f"{image_id} linux amd64"
        assert command[:2] == ["docker", "inspect"]
        return json.dumps({"network_mode": "none", "image_id": image_id, "exit_code": 0})

    def logged(command, path):
        commands.append(command)
        path.write_text("mock container succeeded\n", encoding="utf-8")
        return 0

    def run(command, **kwargs):
        commands.append(command)
        if command[:3] == ["docker", "run", "--rm"]:
            assert "--network" in command
            return subprocess.CompletedProcess(
                command,
                0,
                stdout=json.dumps({"tasks": [], "packaged_file_sha256": packaged}),
            )
        assert command[:2] == ["docker", "rm"]
        return subprocess.CompletedProcess(command, 0)

    verify_files = verify_docker.verify_packaged_files
    monkeypatch.setattr(verify_docker, "capture", capture)
    monkeypatch.setattr(verify_docker, "logged", logged)
    monkeypatch.setattr(verify_docker.subprocess, "run", run)
    monkeypatch.setattr(
        verify_docker, "verify_packaged_files", lambda files: verify_files(files, root=runtime_root)
    )
    destination = tmp_path / "verification"

    exit_code = verify_docker.main(["--skip-build", "--out", str(destination)])

    receipt = json.loads((destination / "report.json").read_text(encoding="utf-8"))
    assert exit_code == 1
    assert receipt["status"] == "failed"
    assert receipt["workspace_matches_image"] is False
    assert receipt["image_id"] == image_id
    assert "new_submission_module.py" in receipt["error"]
    assert not any(command[:2] == ["docker", "build"] for command in commands)
    output = capsys.readouterr().out
    assert "FAIL:" in output
    assert "PASS:" not in output
